#!/usr/bin/env node
/**
 * Builds the docs site and puts it inside the web client's build output, so
 * the client image serves the docs at https://tidepost.example.com/docs/.
 *
 *   node scripts/docs/build-into-client.mjs            build the docs, copy them, audit the copy
 *   node scripts/docs/build-into-client.mjs --check    build the docs and audit them, copy nothing
 *
 * Run AFTER the client build, never as part of it. See the loud comment in
 * packages/client/Dockerfile: the client's build output is also written by the
 * end-to-end suite and by the native shells' builds, and only the web image
 * should carry the docs.
 *
 * A folder of the main domain rather than a host of its own, because one
 * domain keeps all the search authority in one place. And a folder of THIS
 * image rather than a second application or a proxy path, because it then
 * needs no routing at all: the proxy merges the site blocks of two
 * applications that claim the same host, and a proxy path strips the prefix
 * that a "/docs/" build needs to keep.
 *
 * The costs are deliberate and small. A docs-only change rebuilds and
 * redeploys the client image, which never restarts the server. And the image
 * build installs the docs site's dependencies.
 *
 * What it checks for, after building, is the class of failure that looks
 * exactly like success: a page that asks search engines not to index it, a
 * canonical link to an address the site is not served from, a sitemap
 * pointing somewhere else, a robots file that nothing will ever read. Any of
 * them and the build fails here.
 *
 * Generated by hatchkit (feature: docs-in-client), which owns this file and
 * rewrites it on every `hatchkit update`. Change it at the source instead.
 */

import { spawnSync } from "node:child_process";
import { cpSync, existsSync, readFileSync, readdirSync, rmSync, statSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/** The repository root, from this file's own location. */
export const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");

/** The workspace package holding the docs site, and where its build lands. */
export const DOCS_PACKAGE = "docs-site";
export const DOCS_BUILD_DIR = resolve(REPO_ROOT, "docs-site/build");

/**
 * Where the docs are published. A LITERAL, and indexing is always on.
 *
 * Not a variable with a fallback, which is the shape that fails: a docs
 * config that reads its address from the environment falls back to a
 * placeholder, and a placeholder address is paired with noindex, no sitemap
 * and a "Disallow: /" robots file — correctly, because a placeholder must
 * not be indexed. Forget the variable in one build environment and the
 * shipped site carries all three, with nothing failing anywhere.
 *
 * These two must match `url` + `baseUrl` in the docs site's own config,
 * which must also spell them as literals. The audit below is what enforces
 * it: a config that disagrees produces canonical links and sitemap entries
 * outside this prefix, and the build stops.
 */
export const PUBLISHED_PREFIX = "https://tidepost.example.com/docs/";
export const DOCS_BASE_PATH = "/docs/";

/**
 * Where the client's build output is, in the order to look.
 *
 * A statically exported client writes `out/`, and that is what the image
 * serves. A server-rendered client serves `public/` verbatim, and its
 * runtime stage copies that directory, so writing the docs there after the
 * build puts them in the image just the same.
 */
const CLIENT_OUTPUT_CANDIDATES = [
  "packages/client/out",
  "packages/client/public",
];

function clientOutputDir() {
  for (const candidate of CLIENT_OUTPUT_CANDIDATES) {
    const dir = resolve(REPO_ROOT, candidate);
    if (existsSync(dir)) return dir;
  }
  console.error(
    "[docs] No client build output found (" + CLIENT_OUTPUT_CANDIDATES.join(", ") + ")." +
      " Build the client first, or pass --check to audit the docs without copying them.",
  );
  process.exit(1);
}

/** Extensions worth reading. Everything a rule looks at is text; an image or
 *  a font is skipped rather than read into memory and matched against. A file
 *  with no extension of its own (`_headers`, `.htaccess`) counts as text,
 *  because that is the shape a headers file takes. */
const TEXT_EXTENSIONS = [".html", ".xml", ".txt", ".json", ".toml", ".md", ".webmanifest"];

function isTextPath(path) {
  const base = path.slice(path.lastIndexOf("/") + 1);
  if (!base.slice(1).includes(".")) return true;
  return TEXT_EXTENSIONS.some((ext) => base.endsWith(ext));
}

/** Every text file below `dir`, as { relative POSIX path: contents }. */
export function readDocsTree(dir) {
  const files = {};
  const walk = (current) => {
    for (const name of readdirSync(current).sort()) {
      const path = join(current, name);
      if (statSync(path).isDirectory()) {
        walk(path);
        continue;
      }
      const rel = relative(dir, path).split("\\").join("/");
      if (isTextPath(rel)) files[rel] = readFileSync(path, "utf8");
    }
  };
  walk(dir);
  return files;
}

// ---------------------------------------------------------------------------
// The rules.
//
// Generated from one list that the project's own test suite also drives, so
// the checks that run here and the checks that are tested cannot drift apart.
// Edit them at the source (hatchkit: cli/src/features/docs-in-client/rules.ts)
// rather than here.
// ---------------------------------------------------------------------------

const RULES = [
  {
    // A single noindex directive removes the page from every search engine,
    // and nothing about the served page looks wrong. It arrives by accident:
    // a docs config that falls back to a placeholder address turns indexing
    // off along with it, so one unset variable in this build ships the whole
    // site unindexable.
    code: "noindex",
    check({ files }) {
      const robotsMeta = /<meta[^>]*(?:name=["'](?:robots|googlebot)["']|http-equiv=["']x-robots-tag["'])[^>]*>/gi;
      const headerLine = /^[^\n]*x-robots-tag[^\n]*noindex/im;
      const out = [];
      for (const path of Object.keys(files)) {
        const contents = files[path];
        if (path.endsWith(".html")) {
          const tag = (contents.match(robotsMeta) || []).find((t) => /noindex/i.test(t));
          if (tag) {
            out.push({
              code: "noindex",
              path,
              detail: "carries " + tag.trim() + ", which asks search engines not to index it",
            });
          }
          continue;
        }
        if (headerLine.test(contents)) {
          out.push({
            code: "noindex",
            path,
            detail: "sets an X-Robots-Tag noindex header over the docs tree",
          });
        }
      }
      return out;
    },
  },
  {
    // A canonical link pointing somewhere else hands the page's ranking to
    // that address, and an address that does not exist gets nothing. It is
    // what a docs build produces when it was given the wrong site URL or the
    // wrong base path — the pages still serve correctly from the right place.
    code: "canonical-outside-prefix",
    check({ files, publishedPrefix }) {
      const canonical = /<link[^>]*rel=["']canonical["'][^>]*href=["']([^"']+)["']/i;
      // A 404 page is only ever served with a 404 status, which nothing
      // indexes, and the generator gives it a canonical of its own file path.
      const exempt = new Set(["404.html", "404/index.html"]);
      const out = [];
      for (const path of Object.keys(files)) {
        if (!path.endsWith(".html") || exempt.has(path)) continue;
        const match = files[path].match(canonical);
        const href = match && match[1];
        if (!href) {
          out.push({
            code: "canonical-outside-prefix",
            path,
            detail: "has no canonical link, so a crawler picks the address it happens to find",
          });
          continue;
        }
        if (!href.startsWith(publishedPrefix)) {
          out.push({
            code: "canonical-outside-prefix",
            path,
            detail: "points its canonical at " + href + ", which is not under " + publishedPrefix,
          });
        }
      }
      return out;
    },
  },
  {
    // The domain's robots.txt points crawlers at the docs sitemap, so the
    // sitemap is how the docs are discovered at all. One that lists another
    // host, or lists nothing, or was never written because the generator
    // turned sitemaps off along with indexing, sends every crawler that
    // follows robots.txt to a dead end.
    code: "sitemap-entry-outside-prefix",
    check({ files, publishedPrefix }) {
      const sitemapFile = /(^|\/)sitemap[^/]*\.xml$/;
      const out = [];
      const sitemaps = Object.keys(files).filter((path) => sitemapFile.test(path));
      if (sitemaps.length === 0) {
        return [
          {
            code: "sitemap-entry-outside-prefix",
            path: "sitemap.xml",
            detail:
              "was never written, and the domain's robots.txt points crawlers at " +
              publishedPrefix +
              "sitemap.xml",
          },
        ];
      }
      let entries = 0;
      for (const path of sitemaps) {
        const locs = [...files[path].matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1].trim());
        entries += locs.length;
        for (const loc of locs) {
          if (loc.startsWith(publishedPrefix)) continue;
          out.push({
            code: "sitemap-entry-outside-prefix",
            path,
            detail: "lists " + loc + ", which is not under " + publishedPrefix,
          });
        }
      }
      if (entries === 0) {
        out.push({
          code: "sitemap-entry-outside-prefix",
          path: sitemaps[0],
          detail: "lists no pages at all",
        });
      }
      return out;
    },
  },
  {
    // A domain has exactly one robots.txt, the one served from its root, and
    // that one belongs to the web app. A second file under the docs path is
    // never read by a crawler, so whatever it allows or disallows is a belief
    // about the site that is not true — and the generator writes a
    // "Disallow: /" one by default when it thinks its address is a placeholder.
    code: "robots-under-docs-prefix",
    check({ files }) {
      return Object.keys(files)
        .filter((path) => path === "robots.txt" || path.endsWith("/robots.txt"))
        .map((path) => ({
          code: "robots-under-docs-prefix",
          path,
          detail: "is not served to anyone: the domain's robots.txt is the web app's",
        }));
    },
  },
];

/** Everything wrong with a built docs tree: { ok, violations }. Each
 *  violation is { code, path, detail } — the code is stable, the prose is
 *  what tells you what to change. */
export function auditDocsTree(dir, publishedPrefix = PUBLISHED_PREFIX) {
  const input = { files: readDocsTree(dir), publishedPrefix };
  const violations = RULES.flatMap((rule) => rule.check(input));
  return { ok: violations.length === 0, violations };
}

function buildDocs() {
  const build = spawnSync("pnpm", ["--filter", DOCS_PACKAGE, "run", "build"], {
    cwd: REPO_ROOT,
    stdio: "inherit",
  });
  if (build.status !== 0) {
    console.error("[docs] The docs site failed to build.");
    process.exit(build.status ?? 1);
  }
}

function run(argv) {
  // --check builds and audits without copying: a pull request wants to know
  // that the docs still build, that every internal link still resolves and
  // that the pages would be indexed, and none of that needs a client build.
  const checkOnly = argv.includes("--check");

  buildDocs();

  let tree = DOCS_BUILD_DIR;
  if (!checkOnly) {
    const target = join(clientOutputDir(), DOCS_BASE_PATH);
    rmSync(target, { recursive: true, force: true });
    cpSync(DOCS_BUILD_DIR, target, { recursive: true });
    tree = target;
  }

  const { ok, violations } = auditDocsTree(tree);
  if (!ok) {
    console.error("[docs] " + relative(REPO_ROOT, tree) + " is not fit to ship:");
    for (const v of violations) {
      console.error("  - " + v.path + " " + v.detail + " [" + v.code + "]");
    }
    process.exit(1);
  }

  if (checkOnly) {
    console.log("[docs] " + relative(REPO_ROOT, tree) + " would be indexed at " + PUBLISHED_PREFIX);
    return;
  }
  console.log("[docs] Copied the docs to " + relative(REPO_ROOT, tree) + ", served at " + PUBLISHED_PREFIX);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  run(process.argv.slice(2));
}
