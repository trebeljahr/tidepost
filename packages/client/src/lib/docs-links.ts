/**
 * Where the docs are, for every page that links to them.
 *
 * ABSOLUTE, and always reached with a plain <a>, never the router's
 * client-side navigation. Two reasons, both of which only bite in
 * production:
 *
 *   1. Another image of this same app is served on other domains — a
 *      self-hosted instance, a preview deployment — and /docs/ does not
 *      exist there. A relative link would point at nothing; an absolute one
 *      sends the reader to the docs that are actually published.
 *   2. /docs/ is not a route this app has. It is a separate site copied
 *      into the build output by
 *      scripts/docs/build-into-client.mjs, so the router
 *      cannot navigate to it — it has to be a real document request.
 *
 * Keep this in step with PUBLISHED_PREFIX in
 * scripts/docs/build-into-client.mjs; the copy step fails the
 * build when the docs are not published here.
 *
 * Generated by hatchkit (feature: docs-in-client), which owns this file and
 * rewrites it on every `hatchkit update`. Anything you add here is lost;
 * import DOCS_URL from a module of your own instead.
 */
export const DOCS_URL = "https://tidepost.example.com/docs/";

/** A page inside the docs, e.g. `docsUrl("self-hosting")`. */
export function docsUrl(path: string): string {
  return DOCS_URL + path.replace(/^\/+/, "");
}
